// Bundles scripts/composer-entry.mjs (@hc/aistudio composeDeckFile + its
// dependency graph) into backend/internal/composer/composer.js, a single
// self-contained IIFE the Go binary embeds (go:embed) and executes under goja
// (F40 E03). The output is COMMITTED, like the crdt fold bundle, so
// `go build`/`go test` never depend on a Node toolchain being present.
// Re-run via `npm run gen:composer` after changing @hc/aistudio's compose
// path (build:packages first so dist reflects the source).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "scripts/composer-entry.mjs")],
  outfile: path.join(root, "backend/internal/composer/composer.js"),
  bundle: true,
  format: "iife",
  // goja parses ES2017-ish syntax; es2016 keeps the emitted code comfortably
  // inside what it accepts (same target as the crdt fold bundle).
  target: "es2016",
  platform: "neutral",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  legalComments: "none",
  banner: {
    js: "// GENERATED by scripts/build-composer.mjs - do not edit by hand.",
  },
  logLevel: "info",
});
