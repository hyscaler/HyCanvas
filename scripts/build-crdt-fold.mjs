// Bundles scripts/crdt-fold-entry.mjs (yjs + y-protocols + @hc/realtime
// docToFile) into backend/internal/crdt/fold.js, a single self-contained IIFE
// the Go binary embeds (go:embed) and executes under goja. The output is
// COMMITTED, like the gen:theme outputs, so `go build`/`go test` never depend
// on a Node toolchain being present. Re-run via `npm run gen:crdt-fold` after
// bumping yjs or changing @hc/realtime's docToFile.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "scripts/crdt-fold-entry.mjs")],
  outfile: path.join(root, "backend/internal/crdt/fold.js"),
  bundle: true,
  format: "iife",
  // goja implements ES2017+ (no optional chaining/nullish in older releases);
  // es2016 keeps the emitted syntax comfortably inside what goja parses.
  target: "es2016",
  platform: "neutral",
  mainFields: ["module", "main"],
  conditions: ["import", "default"],
  legalComments: "none",
  banner: {
    js: "// GENERATED by scripts/build-crdt-fold.mjs - do not edit by hand.",
  },
  logLevel: "info",
});
