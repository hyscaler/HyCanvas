// Write the Go door's copy of the kit vocabulary from the built package.
//
// The outline prompt names the styles a deck can be set in, the drawings a
// page can carry and the signature forms, and the Go door builds that
// prompt natively (backend/internal/aistudio/generate.go). The names and
// the clause come from @hc/aistudio's generated tables, so they are written
// into Go from the package's build rather than kept by hand; a Go test
// (backend/internal/composer) holds the two copies identical.
//
// Run: npm run build -w packages/aistudio && node scripts/gen-kit-vocab.mjs

import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "backend", "internal", "aistudio", "kitvocab_gen.go");
const { kitStyleNames, kitDrawingNames, kitSignatures, kitVocabularyRule } = await import(join(ROOT, "packages", "aistudio", "dist", "index.js"));

const set = (name, items) => `var ${name} = map[string]bool{\n${items.map((s) => `\t${JSON.stringify(s)}: true,`).join("\n")}\n}`;
const src = `// Code generated by scripts/gen-kit-vocab.mjs from @hc/aistudio. DO NOT EDIT.
//
// The kit vocabulary the outline prompt carries: the styles a deck can be
// set in, the drawings a page can name, the signature forms, and the clause
// that states them. Mirrors kit/vocab.ts in the composer package.

package aistudio

${set("kitStyles", kitStyleNames)}

${set("kitDrawings", kitDrawingNames)}

${set("kitSignatures", [...kitSignatures])}

// kitVocabularyRule is appended to the outline system prompt, word for word
// with kitVocabularyRule in kit/vocab.ts.
const kitVocabularyRule = ${JSON.stringify(kitVocabularyRule)}
`;
writeFileSync(OUT, src);
execFileSync("gofmt", ["-w", OUT]);
console.log(`wrote ${OUT}: ${kitStyleNames.length} styles, ${kitDrawingNames.length} drawings, ${kitSignatures.length} signatures, rule ${kitVocabularyRule.length} chars`);
